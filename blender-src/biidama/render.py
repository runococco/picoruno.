def sprite_cam(sc, scale, res, tz=0.0):
    """same elevation as the room camera, ortho, square; returns world (x, z) at y=0 -> sprite px"""
    for o in list(sc.objects):
        if o.type == 'CAMERA': bpy.data.objects.remove(o)
    e = math.radians(ELEV); d = 30; tgt = Vector((0, 0, tz)); loc = tgt + Vector((0, -math.cos(e) * d, math.sin(e) * d))
    bpy.ops.object.camera_add(location=loc); c = bpy.context.object; c.rotation_euler = (tgt - loc).to_track_quat('-Z', 'Y').to_euler()
    c.data.type = 'ORTHO'; c.data.ortho_scale = scale; c.data.clip_end = 100; sc.camera = c
def side_cam(sc, scale, res, tz, tx=0.0):
    for o in list(sc.objects):
        if o.type == 'CAMERA': bpy.data.objects.remove(o)
    loc = Vector((tx, -30, tz)); bpy.ops.object.camera_add(location=loc); c = bpy.context.object; c.rotation_euler = (math.radians(90), 0, 0)
    c.data.type = 'ORTHO'; c.data.ortho_scale = scale; c.data.clip_end = 100; sc.camera = c
    sc.render.resolution_x = sc.render.resolution_y = res; bpy.context.view_layer.update()
    return lambda x, z: [round(res / 2 + (x - tx) * res / scale, 1), round(res / 2 - (z - tz) * res / scale, 1)]

def disc(loc, r, m, depth=0.01, verts=48):
    """flat painted disc facing the camera (-y)"""
    return cyl(loc, r, depth, m, verts, rot=(math.radians(90), 0, 0))

def paint_on(base_loc, base_scale, m, cutter_loc, cutter_scale, seg=48, rot=(0, 0, 0)):
    o = sphere(base_loc, tuple(v * 1.012 for v in base_scale), m, seg, rot)
    bpy.ops.mesh.primitive_uv_sphere_add(segments=32, ring_count=16, location=cutter_loc); c = bpy.context.object; c.scale = cutter_scale; c.hide_render = True
    bo = o.modifiers.new('b', 'BOOLEAN'); bo.object = c; bo.operation = 'INTERSECT'; return o
def box(loc, sc_, m, bev=0.02):
    bpy.ops.mesh.primitive_cube_add(size=1, location=loc); o = bpy.context.object; o.scale = sc_; o.data.materials.append(m); bevel(o, bev, 3); return o
def tp(x, y): return [round(RES[0] / 2 + x * PXU, 1), round(RES[1] / 2 - y * PXU, 1)]


LV = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'levels.json')))['levels']
def gw(x, y): return ((x - RES[0] / 2) / PXU, (RES[1] / 2 - y) / PXU)
def board(sc, lv):
    tbl = wood('table', '#8a6040', '#9a7050'); box((0, 0, -0.8), (9, 12, 0.4), tbl, 0.0)
    floor = noise_mat('floor', '#e8c898', '#f2d6a8', 4, 0.75, 0.1); frame = wood('frame', '#a87040', '#b88050')
    x0, y0 = gw(40, 190); x1, y1 = gw(680, 1170)
    box(((x0 + x1) / 2, (y0 + y1) / 2, -0.55), (x1 - x0, y0 - y1, 0.12), floor, 0.0)
    t = 20 / PXU
    for (x, y, w, h) in ((40, 190, 640, 20), (40, 1150, 640, 20), (40, 190, 20, 980), (660, 190, 20, 980)):
        cx, cy = gw(x + w / 2, y + h / 2); box((cx, cy, -0.4), (w / PXU, h / PXU, 0.3), frame, 0.02)
    wm = wood('wall', '#c08850', '#cc9860')
    for (x, y, w, h) in lv['walls']:
        cx, cy = gw(x + w / 2, y + h / 2); box((cx, cy, -0.42), (w / PXU, h / PXU, 0.22), wm, 0.02)
    hole = mat('hole', '#1a120c', 0.9); rim = mat('rim', '#6a4a2a', 0.8)
    for (x, y) in lv['holes']:
        cx, cy = gw(x, y); cyl((cx, cy, -0.49), 26 / PXU, 0.01, hole, 48)
        bpy.ops.mesh.primitive_torus_add(major_radius=27 / PXU, minor_radius=0.02, location=(cx, cy, -0.49)); o = bpy.context.object; o.data.materials.append(rim)
    gx, gy = gw(*lv['goal']); gold = mat('goal', '#f2c14e', 0.35, 0.5)
    bpy.ops.mesh.primitive_torus_add(major_radius=30 / PXU, minor_radius=0.04, location=(gx, gy, -0.48)); o = bpy.context.object; o.data.materials.append(gold); smooth(o)
    cyl((gx, gy, -0.5), 26 / PXU, 0.01, mat('goalin', '#c84a3a', 0.6), 48)
def build_boards():
    for i, lv in enumerate(LV):
        sc = reset(True); board(sc, lv); render(sc, f'bg{i}')
def build_marble():
    sc = reset(True); sc.cycles.film_transparent_glass = True
    g = bpy.data.materials.new('glass'); g.use_nodes = True; b = g.node_tree.nodes['Principled BSDF']
    b.inputs['Base Color'].default_value = (*srgb('#7ac8e8'), 1); b.inputs['Roughness'].default_value = 0.05; b.inputs['Transmission Weight'].default_value = 0.55; b.inputs['IOR'].default_value = 1.45
    sphere((0, 0, 0), (0.12, 0.12, 0.12), g, 64)
    # coloured swirl inside
    sw = mat('swirl', '#e8584a', 0.4, 0.3)
    bpy.ops.mesh.primitive_torus_add(major_radius=0.07, minor_radius=0.026, location=(0, 0, 0)); o = bpy.context.object; o.rotation_euler = (0.6, 0.3, 0); o.data.materials.append(sw); smooth(o)
    sprite_cam(sc, 0.32, 96); sc.render.resolution_x = sc.render.resolution_y = 96; render(sc, 'marble')

JOBS = {'boards': build_boards, 'marble': build_marble}
for k in (JOBS.keys() if WHAT == 'all' else WHAT.split(',')):
    JOBS[k]()
json.dump({'levels': len(LV)}, open(os.path.join(OUT, 'scene.json'), 'w'))
